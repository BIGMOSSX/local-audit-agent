use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::ffi::OsString;
use std::io::{self, BufRead, BufReader, Read, Write};
use std::path::PathBuf;
use std::process::{Child, ChildStdin, Command, Stdio};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{mpsc, Mutex};
use std::thread;
use std::time::{Duration, Instant};

const HANDSHAKE_TIMEOUT: Duration = Duration::from_secs(15);
const CONNECT_ATTEMPTS: u32 = 5;
const CONNECT_BACKOFF: Duration = Duration::from_millis(50);
/// Default I/O timeout; see `timeout_for` for the methods that get longer.
const IO_TIMEOUT: Duration = Duration::from_secs(30);
const SHUTDOWN_GRACE: Duration = Duration::from_secs(2);

/// Longer ceilings for methods that legitimately take a while. A timeout still discards
/// (kills) the daemon. `audit.run` is not one of them: it starts a background run and returns.
fn timeout_for(method: &str) -> Duration {
    match method {
        "audit.plan" => Duration::from_secs(60),
        "agent.chat" => Duration::from_secs(120),
        "tools.install" | "tools.remove" | "models.configure" => Duration::from_secs(300),
        _ => IO_TIMEOUT,
    }
}

/// Serialized to the webview as `{ "code": …, "message": … }`.
/// Messages are fixed strings: never the session token, the endpoint path or OS error text.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct IpcFailure {
    pub code: String,
    pub message: String,
}

impl IpcFailure {
    pub fn new(code: &str, message: impl Into<String>) -> Self {
        Self {
            code: code.to_string(),
            message: message.into(),
        }
    }
}

#[derive(Debug, Clone)]
pub struct SidecarSpec {
    pub node: OsString,
    pub entry: Option<PathBuf>,
    pub data_dir: PathBuf,
}

// No `Debug`: it holds the session token.
#[derive(Deserialize)]
struct Handshake {
    ready: bool,
    endpoint: String,
    token: String,
}

// No `Debug`: it holds the session token.
struct Running {
    child: Child,
    // Held only so the pipe stays open; dropping it tells the daemon to exit.
    _stdin: ChildStdin,
    endpoint: String,
    token: String,
}

impl Running {
    /// Closing stdin asks the daemon to exit (it then removes its own socket
    /// directory); only a daemon that ignores that for `SHUTDOWN_GRACE` is killed.
    fn kill(self) {
        let Running {
            mut child,
            _stdin: stdin,
            endpoint,
            ..
        } = self;
        drop(stdin);
        let deadline = Instant::now() + SHUTDOWN_GRACE;
        while matches!(child.try_wait(), Ok(None)) && Instant::now() < deadline {
            thread::sleep(Duration::from_millis(20));
        }
        if matches!(child.try_wait(), Ok(None)) {
            let _ = child.kill();
        }
        let _ = child.wait();
        remove_endpoint_dir(&endpoint);
    }
}

/// A killed daemon cannot clean up after itself; remove its `audit-*` socket
/// directory (never any other directory).
#[cfg(unix)]
fn remove_endpoint_dir(endpoint: &str) {
    if let Some(dir) = std::path::Path::new(endpoint).parent() {
        let is_ours = dir
            .file_name()
            .is_some_and(|name| name.to_string_lossy().starts_with("audit-"));
        if is_ours {
            let _ = std::fs::remove_dir_all(dir);
        }
    }
}

#[cfg(windows)]
fn remove_endpoint_dir(_endpoint: &str) {}

pub struct Sidecar {
    spec: SidecarSpec,
    running: Mutex<Option<Running>>,
    next_id: AtomicU64,
}

fn unavailable(message: impl Into<String>) -> IpcFailure {
    IpcFailure::new("sidecar_unavailable", message)
}

fn fail(mut child: Child, message: &str) -> IpcFailure {
    let _ = child.kill();
    let _ = child.wait();
    unavailable(message)
}

fn spawn(spec: &SidecarSpec) -> Result<Running, IpcFailure> {
    let entry = spec
        .entry
        .as_ref()
        .ok_or_else(|| unavailable("The local service is not bundled in this build."))?;

    // The session token is generated by the daemon and only ever travels back
    // over its stdout: nothing secret goes into argv or the environment.
    let mut command = Command::new(&spec.node);
    command
        .arg(entry)
        .arg("--data-dir")
        .arg(&spec.data_dir)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(if cfg!(debug_assertions) {
            Stdio::inherit()
        } else {
            Stdio::null()
        });
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt; // verify at compile time
        command.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
    }

    let mut child = command
        .spawn()
        .map_err(|_| unavailable("Could not start the local service."))?;
    let (stdin, stdout) = match (child.stdin.take(), child.stdout.take()) {
        (Some(i), Some(o)) => (i, o),
        _ => return Err(fail(child, "The local service has no usable pipes.")),
    };

    let (tx, rx) = mpsc::channel::<io::Result<String>>();
    thread::spawn(move || {
        let mut reader = BufReader::new(stdout);
        let mut line = String::new();
        let first = reader.read_line(&mut line).map(|_| line);
        let _ = tx.send(first);
        // Keep draining so the daemon can never block on a full stdout pipe.
        let _ = io::copy(&mut reader, &mut io::sink());
    });

    let line = match rx.recv_timeout(HANDSHAKE_TIMEOUT) {
        Ok(Ok(line)) if !line.trim().is_empty() => line,
        Ok(_) => return Err(fail(child, "The local service exited before it was ready.")),
        Err(_) => {
            return Err(fail(
                child,
                "The local service did not become ready in time.",
            ))
        }
    };
    // Never put `line` in an error message: it contains the session token.
    let handshake: Handshake = match serde_json::from_str(line.trim()) {
        Ok(h) => h,
        Err(_) => {
            return Err(fail(
                child,
                "The local service sent an unreadable handshake.",
            ))
        }
    };
    if !handshake.ready {
        return Err(fail(child, "The local service reported it is not ready."));
    }
    Ok(Running {
        child,
        _stdin: stdin,
        endpoint: handshake.endpoint,
        token: handshake.token,
    })
}

enum Exchange {
    /// The connection could not be made, so the request was never delivered.
    Connect,
    /// Something failed after the request may have been delivered.
    Io(io::Error),
}

fn retry<T>(mut attempt: impl FnMut() -> io::Result<T>) -> io::Result<T> {
    let mut last = None;
    for n in 0..CONNECT_ATTEMPTS {
        match attempt() {
            Ok(value) => return Ok(value),
            Err(e) => last = Some(e),
        }
        if n + 1 < CONNECT_ATTEMPTS {
            thread::sleep(CONNECT_BACKOFF);
        }
    }
    Err(last.unwrap_or_else(|| io::Error::other("no connection attempt was made")))
}

#[cfg(unix)]
fn connect(endpoint: &str) -> io::Result<std::os::unix::net::UnixStream> {
    retry(|| std::os::unix::net::UnixStream::connect(endpoint))
}

// A Windows named pipe opens like a file; the daemon side is Node's `net` server.
// Neither platform relies on socket timeouts: `exchange` bounds the read itself.
#[cfg(windows)]
fn connect(endpoint: &str) -> io::Result<std::fs::File> {
    retry(|| {
        std::fs::OpenOptions::new()
            .read(true)
            .write(true)
            .open(endpoint)
    })
}

fn round_trip<S: Read + Write>(mut stream: S, line: &str) -> io::Result<String> {
    stream.write_all(line.as_bytes())?;
    stream.flush()?;
    let mut reader = BufReader::new(stream);
    let mut reply = String::new();
    if reader.read_line(&mut reply)? == 0 {
        return Err(io::Error::new(
            io::ErrorKind::UnexpectedEof,
            "the local service closed the connection",
        ));
    }
    Ok(reply)
}

fn exchange(
    endpoint: &str,
    token: &str,
    id: u64,
    method: &str,
    params: Option<&Value>,
    timeout: Duration,
) -> Result<String, Exchange> {
    let mut request = json!({ "id": id, "token": token, "method": method });
    if let Some(params) = params {
        request["params"] = params.clone();
    }
    let line = format!("{request}\n");
    let stream = connect(endpoint).map_err(|_| Exchange::Connect)?;
    // The read runs on its own thread so a hung daemon cannot block the caller
    // (a Windows pipe has no read timeout). On timeout the thread ends when the
    // caller kills the daemon and the pipe closes.
    let (tx, rx) = mpsc::channel();
    thread::spawn(move || {
        let _ = tx.send(round_trip(stream, &line));
    });
    match rx.recv_timeout(timeout) {
        Ok(result) => result.map_err(Exchange::Io),
        Err(_) => Err(Exchange::Io(io::Error::new(
            io::ErrorKind::TimedOut,
            "the local service did not answer in time",
        ))),
    }
}

#[derive(Deserialize)]
struct Reply {
    id: Option<Value>,
    ok: bool,
    result: Option<Value>,
    error: Option<ReplyError>,
}

#[derive(Deserialize)]
struct ReplyError {
    code: String,
    message: String,
}

fn protocol_failure() -> IpcFailure {
    IpcFailure::new(
        "sidecar_protocol",
        "The local service sent an unreadable reply.",
    )
}

fn interpret(line: &str, id: u64) -> Result<Value, IpcFailure> {
    let reply: Reply = serde_json::from_str(line.trim()).map_err(|_| protocol_failure())?;
    if reply.ok {
        if reply.id != Some(json!(id)) {
            return Err(protocol_failure());
        }
        Ok(reply.result.unwrap_or(Value::Null))
    } else {
        let error = reply.error.ok_or_else(protocol_failure)?;
        Err(IpcFailure {
            code: error.code,
            message: error.message,
        })
    }
}

impl Sidecar {
    pub fn new(spec: SidecarSpec) -> Self {
        Self {
            spec,
            running: Mutex::new(None),
            next_id: AtomicU64::new(1),
        }
    }

    /// Returns the live daemon's (endpoint, token), starting one if needed.
    /// `replace` names an endpoint the caller could not reach: it is restarted
    /// only if it is still the current one (another caller may have restarted it already).
    fn ensure_running(&self, replace: Option<&str>) -> Result<(String, String), IpcFailure> {
        let mut guard = self
            .running
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        let running = match guard.take() {
            None => spawn(&self.spec)?,
            Some(mut current) => {
                if replace == Some(current.endpoint.as_str()) {
                    current.kill();
                    spawn(&self.spec)?
                } else if matches!(current.child.try_wait(), Ok(None)) {
                    current
                } else {
                    let _ = current.child.wait();
                    remove_endpoint_dir(&current.endpoint);
                    spawn(&self.spec)?
                }
            }
        };
        let out = (running.endpoint.clone(), running.token.clone());
        *guard = Some(running);
        Ok(out)
    }

    /// Stops the daemon at `endpoint` if it is still the current one; the next call starts a fresh one.
    fn discard(&self, endpoint: &str) {
        let mut guard = self
            .running
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        if guard.as_ref().is_some_and(|r| r.endpoint == endpoint) {
            if let Some(running) = guard.take() {
                running.kill();
            }
        }
    }

    /// Retries once, and only when the connection could not be made at all
    /// (so the request was never delivered and cannot be applied twice).
    pub fn call(&self, method: &str, params: Option<Value>) -> Result<Value, IpcFailure> {
        let timeout = timeout_for(method);
        let mut unreachable: Option<String> = None;
        for attempt in 0..2 {
            let (endpoint, token) = self.ensure_running(unreachable.as_deref())?;
            let id = self.next_id.fetch_add(1, Ordering::Relaxed);
            match exchange(&endpoint, &token, id, method, params.as_ref(), timeout) {
                Ok(line) => return interpret(&line, id),
                Err(Exchange::Connect) if attempt == 0 => unreachable = Some(endpoint),
                Err(Exchange::Connect) => {
                    return Err(unavailable("Could not reach the local service."))
                }
                Err(Exchange::Io(e)) => {
                    let message = if e.kind() == io::ErrorKind::TimedOut {
                        self.discard(&endpoint);
                        "The local service did not answer in time."
                    } else {
                        "Lost contact with the local service."
                    };
                    return Err(IpcFailure::new("sidecar_io", message));
                }
            }
        }
        Err(unavailable("Could not reach the local service."))
    }

    /// Gracefully stops the daemon (stdin close, then kill after the grace period) and removes its
    /// endpoint dir. Called on app exit, where `Drop` never runs; safe to call repeatedly.
    pub fn shutdown(&self) {
        let mut guard = self
            .running
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        if let Some(running) = guard.take() {
            running.kill();
        }
    }

    /// Kills and reaps the daemon but leaves its entry in place, so the next
    /// call sees a dead child and respawns: the exact `kill -9` path.
    #[doc(hidden)]
    pub fn kill_for_test(&self) {
        let mut guard = self
            .running
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        if let Some(running) = guard.as_mut() {
            let _ = running.child.kill();
            let _ = running.child.wait();
        }
    }

    #[doc(hidden)]
    pub fn endpoint_for_test(&self) -> Option<String> {
        let guard = self
            .running
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        guard.as_ref().map(|r| r.endpoint.clone())
    }
}

impl Drop for Sidecar {
    fn drop(&mut self) {
        let slot = self
            .running
            .get_mut()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        if let Some(running) = slot.take() {
            running.kill();
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Cursor;

    struct Fake {
        input: Cursor<Vec<u8>>,
        output: Vec<u8>,
    }
    impl Read for Fake {
        fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
            self.input.read(buf)
        }
    }
    impl Write for Fake {
        fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
            self.output.write(buf)
        }
        fn flush(&mut self) -> io::Result<()> {
            Ok(())
        }
    }

    #[test]
    fn interprets_success_and_returns_the_result() {
        let line = r#"{"id":7,"ok":true,"result":{"projects":[]}}"#;
        assert_eq!(interpret(line, 7).unwrap(), json!({ "projects": [] }));
    }

    #[test]
    fn a_success_without_a_result_is_null() {
        assert_eq!(interpret(r#"{"id":1,"ok":true}"#, 1).unwrap(), Value::Null);
    }

    #[test]
    fn passes_daemon_errors_through_with_their_code() {
        let line =
            r#"{"id":null,"ok":false,"error":{"code":"unauthorized","message":"Unauthorized."}}"#;
        assert_eq!(
            interpret(line, 1).unwrap_err(),
            IpcFailure::new("unauthorized", "Unauthorized.")
        );
    }

    #[test]
    fn a_mismatched_id_is_a_protocol_failure() {
        assert_eq!(
            interpret(r#"{"id":2,"ok":true}"#, 1).unwrap_err().code,
            "sidecar_protocol"
        );
    }

    #[test]
    fn garbage_is_a_protocol_failure() {
        for line in ["", "not json", "[]", r#"{"ok":false}"#, r#"{"id":1}"#] {
            assert_eq!(
                interpret(line, 1).unwrap_err().code,
                "sidecar_protocol",
                "{line:?}"
            );
        }
    }

    #[test]
    fn failures_serialize_to_the_shape_the_frontend_expects() {
        let value = serde_json::to_value(IpcFailure::new("invalid_path", "nope")).unwrap();
        assert_eq!(value, json!({ "code": "invalid_path", "message": "nope" }));
    }

    #[test]
    fn round_trip_writes_the_line_and_reads_one_reply_line() {
        let fake = Fake {
            input: Cursor::new(b"{\"ok\":true}\nleftover".to_vec()),
            output: Vec::new(),
        };
        let reply = round_trip(fake, "hello\n").unwrap();
        assert_eq!(reply, "{\"ok\":true}\n");
    }

    #[test]
    fn round_trip_reports_eof_as_an_error() {
        let fake = Fake {
            input: Cursor::new(Vec::new()),
            output: Vec::new(),
        };
        assert_eq!(
            round_trip(fake, "hello\n").unwrap_err().kind(),
            io::ErrorKind::UnexpectedEof
        );
    }

    #[cfg(unix)]
    #[test]
    fn remove_endpoint_dir_only_removes_audit_directories() {
        let base = std::env::temp_dir().join(format!("sidecar-unit-{}", std::process::id()));
        let ours = base.join("audit-abc");
        let other = base.join("keep-me");
        std::fs::create_dir_all(&ours).unwrap();
        std::fs::create_dir_all(&other).unwrap();
        remove_endpoint_dir(ours.join("d.sock").to_str().unwrap());
        remove_endpoint_dir(other.join("d.sock").to_str().unwrap());
        assert!(!ours.exists());
        assert!(other.exists());
        std::fs::remove_dir_all(&base).unwrap();
    }

    #[cfg(unix)]
    #[test]
    fn a_daemon_that_never_answers_times_out_instead_of_hanging() {
        use std::os::unix::net::UnixListener;
        let dir = std::env::temp_dir().join(format!("sidecar-hang-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("hang.sock");
        let listener = UnixListener::bind(&path).unwrap();
        let holder = thread::spawn(move || {
            let (_stream, _) = listener.accept().unwrap();
            thread::sleep(Duration::from_millis(800));
        });
        let started = Instant::now();
        let result = exchange(
            path.to_str().unwrap(),
            "t",
            1,
            "project.list",
            None,
            Duration::from_millis(200),
        );
        match result {
            Err(Exchange::Io(e)) => assert_eq!(e.kind(), io::ErrorKind::TimedOut),
            _ => panic!("expected a timeout"),
        }
        assert!(started.elapsed() < Duration::from_millis(700));
        holder.join().unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn long_running_methods_get_longer_timeouts_than_the_default() {
        assert_eq!(timeout_for("project.list"), Duration::from_secs(30));
        assert!(timeout_for("audit.plan") > timeout_for("project.list"));
        // audit.run only starts a background run, so it must not hold the daemon hostage for minutes.
        assert_eq!(timeout_for("audit.run"), Duration::from_secs(30));
    }

    /// One explicit decision per allowlisted method: adding a method to `ALLOWED_METHODS` fails
    /// `every_allowlisted_method_has_an_explicit_timeout` until it is given a row here.
    const EXPECTED_TIMEOUTS: [(&str, u64); 17] = [
        ("project.open", 30),
        ("project.list", 30),
        ("project.status", 30),
        ("audit.plan", 60),
        ("audit.run", 30),
        ("audit.cancel", 30),
        ("audit.history", 30),
        ("finding.list", 30),
        ("finding.detail", 30),
        ("finding.suppress", 30),
        ("agent.chat", 120),
        ("agent.cancel", 30),
        ("tools.list", 30),
        ("tools.install", 300),
        ("tools.remove", 300),
        ("models.list", 30),
        ("models.configure", 300),
    ];

    #[test]
    fn every_allowlisted_method_has_an_explicit_timeout() {
        use std::collections::BTreeSet;
        let table: BTreeSet<&str> = EXPECTED_TIMEOUTS.iter().map(|(m, _)| *m).collect();
        let allowed: BTreeSet<&str> = crate::allowlist::ALLOWED_METHODS.iter().copied().collect();
        assert_eq!(
            table.len(),
            EXPECTED_TIMEOUTS.len(),
            "duplicate method in EXPECTED_TIMEOUTS"
        );
        assert_eq!(
            table, allowed,
            "EXPECTED_TIMEOUTS must list exactly the allowlisted methods"
        );
        for (method, seconds) in EXPECTED_TIMEOUTS {
            assert_eq!(
                timeout_for(method),
                Duration::from_secs(seconds),
                "{method}"
            );
        }
    }

    #[test]
    fn an_unknown_method_falls_back_to_the_default() {
        assert_eq!(timeout_for("shell.exec"), IO_TIMEOUT);
    }
}
